def format_compact_vehicle_link(vin: str, nick: str) -> str:
    return (f'<a href="#vin-{vin}" class="vehicle-link" '
            f'style="color: #2563eb; text-decoration: underline; text-underline-offset: 3px; font-weight: 600; cursor: pointer;">{esc(nick)}</a>')


def format_compact_faults(vin: str, nick: str, grafana_url: str, items: list) -> str:
    vehicle_link = f'<strong>{format_compact_vehicle_link(vin, nick)}</strong>'
    grafana_link = (f'<a href="{esc(grafana_url)}" target="_blank" '
                    f'style="color: #2563eb; text-decoration: underline; font-size: 11px; font-weight: 600;">Grafana link ↗</a>') if grafana_url else ""
    parts = [vehicle_link]
    if grafana_link:
        parts.append(grafana_link)
    for it in items:
        if it["structured"]:
            title = it["title"]
            sev = it["severity"]
            badge = severity_badge(sev) if sev else ""
            if badge:
                parts.append(f'<strong>{esc(title)} — {badge}</strong>')
            else:
                parts.append(f'<strong>{esc(title)}</strong>')
        elif it["title"]:
            parts.append(f'<strong>{esc(it["title"])}</strong>')
    return " &nbsp;|&nbsp; ".join(parts)


def format_compact_mdm(vin: str, nick: str, grafana_url: str, mdm_items: list, val: dict, issues_str: str) -> str:
    vehicle_link = f'<strong>{format_compact_vehicle_link(vin, nick)}</strong>'
    grafana_link = (f' &nbsp;<a href="{esc(grafana_url)}" target="_blank" '
                    f'style="color: #2563eb; text-decoration: underline; font-size: 11px; font-weight: 600;">Grafana link ↗</a>') if grafana_url else ""
    if mdm_items:
        item_parts = []
        for it in mdm_items:
            desc = (it["description"] or it["title"] or f"VT_BOX online: {val.get('vt_box_time') or 'Not Available'}").strip()
            desc = desc.rstrip(".")
            sev = it.get("severity")
            badge = severity_badge(sev) if sev else ""
            if badge:
                item_parts.append(f"{esc(desc)}. &nbsp;{badge}")
            else:
                item_parts.append(f"{esc(desc)}.")
        desc_str = " &nbsp;|&nbsp; ".join(item_parts)
    else:
        desc = issues_str if issues_str else f"VT_BOX online: {val.get('vt_box_time') or 'Not Available'}"
        desc = desc.rstrip(".")
        desc_str = f"{esc(desc)}."
    return f'{vehicle_link} ({vin}) — {desc_str}{grafana_link}'


def get_issue_summary_section(vehicles: dict, global_duration: str) -> str:
    temp_anomaly_vins = [
        "MD9GBUE27DC341048",  # P1
        "MD9GBUE23DC341063",  # P6
        "MD9GBUE29DC341066",  # P9
        "MD9GBUE22DC341068",  # P11
        "MD9GBUE27DC341079",  # P22
        "MD9GBUE20DC341070",  # P13
        "MD9GBUE24DC341038",  # T9
    ]

    vehicles = normalize_vehicles(vehicles)
    lists = {"mdm": [], "inactive": [], "temp": [], "bms": [],
             "charging": [], "ok": [], "data_loss": []}

    for vin, val in sorted(vehicles.items()):
        status_val = val.get("status", "healthy")
        nick = get_short_nickname(val.get("nickname", ""))
        items = vehicle_issue_items(val)
        issues = [i["title"] for i in items]
        issues_str = ", ".join(issues)

        grafana_url = (val.get("grafana_url") or "").strip()
        grafana_link = (f' &nbsp;<a href="{esc(grafana_url)}" target="_blank" '
                        f'style="color: #2563eb; text-decoration: underline; font-size: 11px; font-weight: 600;">Grafana link ↗</a>') if grafana_url else ""

        has_structured = any(i["structured"] for i in items)

        if status_val == 'mdm_issue':
            if not has_structured:
                lists["mdm"].append(format_compact_mdm(vin, nick, grafana_url, [], val, issues_str))
            else:
                groups = {}
                for it in items:
                    groups.setdefault(
                        _bucket_for(it, status_val), []).append(it)
                mdm_items = groups.pop("mdm", [])
                lists["mdm"].append(format_compact_mdm(vin, nick, grafana_url, mdm_items, val, issues_str))
                for bucket in ("data_loss", "charging", "bms"):
                    if bucket in groups:
                        lists[bucket].append(format_compact_faults(vin, nick, grafana_url, groups[bucket]))
        elif status_val == 'inactive':
            timestamp = val.get("timestamp") or "Not Available"
            lists["inactive"].append(
                f'<strong><span style="color: #64748b;">{nick}</span></strong> — Last updated {timestamp}{grafana_link}')
        elif status_val == 'unhealthy':
            if not has_structured:
                parts = [f'<strong>{format_compact_vehicle_link(vin, nick)}</strong>']
                if grafana_url:
                    parts.append(f'<a href="{esc(grafana_url)}" target="_blank" style="color: #2563eb; text-decoration: underline; font-size: 11px; font-weight: 600;">Grafana link ↗</a>')
                if issues_str:
                    parts.append(f'<strong>{esc(issues_str)}</strong>')
                entry = " &nbsp;|&nbsp; ".join(parts)
                if any("data loss" in issue.lower() for issue in issues):
                    lists["data_loss"].append(entry)
                elif any("plug state 4" in issue.lower() or "charging" in issue.lower() for issue in issues):
                    lists["charging"].append(entry)
                else:
                    lists["bms"].append(entry)
            else:
                groups = {}
                for it in items:
                    groups.setdefault(
                        _bucket_for(it, status_val), []).append(it)
                for bucket in ("mdm", "data_loss", "charging", "bms"):
                    if bucket not in groups:
                        continue
                    if bucket == "mdm":
                        lists["mdm"].append(format_compact_mdm(vin, nick, grafana_url, groups["mdm"], val, issues_str))
                    else:
                        lists[bucket].append(format_compact_faults(vin, nick, grafana_url, groups[bucket]))
        elif status_val == 'healthy':
            lists["ok"].append(
                f'<span style="color:#16a34a; font-weight:600;">{nick}</span>{grafana_link}')

        if vin in temp_anomaly_vins:
            lists["temp"].append(format_compact_vehicle_link(vin, nick))

    def format_row(title, color, text_list, count, is_bold=True, badge_bg=None, badge_color=None):
        if not text_list:
            if title == "Charging Issues (Plug State 4)":
                rendered_text = "None reported"
            else:
                return ""
        else:
            if title == "Motor Controller Temperature (Negative Values)":
                rendered_text = ", ".join(text_list)
            elif title == "✓ OK / No Issues":
                rendered_text = ", ".join(text_list)
            else:
                rendered_text = "<br/>".join(text_list)

        count_badge = "—"
        if count is not None:
            if badge_bg and badge_color:
                count_badge = f'<span style="display: inline-block; padding: 4px 8px; font-size: 11px; font-weight: bold; border-radius: 12px; background-color: {badge_bg}; color: {badge_color};">{count}</span>'
            else:
                count_badge = f'<span style="display: inline-block; padding: 4px 8px; font-size: 11px; font-weight: bold; border-radius: 12px; background-color: #f1f3f5; color: #475569;">{count}</span>'

        title_style = f"color: {color}; font-weight: 600; vertical-align: top;" if is_bold else "color: #475569; vertical-align: top;"

        return f"""
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 12px; border-bottom: 1px solid #f1f5f9; {title_style}">{title}</td>
              <td style="padding: 12px; border-bottom: 1px solid #f1f5f9; color: #475569; vertical-align: top;">{rendered_text}</td>
              <td style="padding: 12px; border-bottom: 1px solid #f1f5f9; text-align: right; vertical-align: top;">{count_badge}</td>
            </tr>
        """

    rows = []
    rows.append(format_row("⚠ MDM ON but No Data Received", "#ea580c", lists["mdm"], len(
        lists["mdm"]), badge_bg="#ffedd5", badge_color="#ea580c"))
    rows.append(format_row("⊘ No Data Reported", "#64748b",
                lists["inactive"], len(lists["inactive"])))
    rows.append(format_row("Motor Controller Temperature (Negative Values)", "#475569",
                lists["temp"], len(lists["temp"]), is_bold=False))
