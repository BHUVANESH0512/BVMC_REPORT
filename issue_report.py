def _csv_safe(value):
    """Stop spreadsheet programs from running a text cell as a formula."""
    if isinstance(value, str) and value and value[0] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + value
    return value


def build_csv_rows(vehicles: dict) -> list:
    rows = []
    serial = 0
    for vin, val in sorted((vehicles or {}).items()):
        if not isinstance(val, dict) or val.get("status") not in ISSUE_STATUSES:
            continue
        for it in vehicle_issue_items(val):
            serial += 1
            rows.append([_csv_safe(c) for c in [
                serial, vin, val.get("nickname", ""), val.get("location", ""),
                it["title"], it["description"], it["period"], it["occurrences"],
                it["component"], it["reported_by"], it["severity"], it["rca"],
                it["responsible_team"], it["customer_feedback"], it["grafana_url"],
            ]])
    return rows
