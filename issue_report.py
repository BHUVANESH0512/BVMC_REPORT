def severity_badge(severity: str) -> str:
    if severity not in SEVERITY_STYLES:
        return ""
    bg, fg = SEVERITY_STYLES[severity]
    return (f'<span style="display: inline-block; padding: 3px 8px; font-size: 10px; font-weight: bold; '
            f'border-radius: 12px; background-color: {bg}; color: {fg}; text-transform: uppercase;">{severity}</span>')


def issue_block_html(item: dict) -> str:
    border = SEVERITY_BORDERS.get(item["severity"], "#cbd5e1")
    badge = severity_badge(item["severity"])
    lines = [f'<strong style="color: #0f172a;">{esc(item["title"])}</strong>' +
             (f' &nbsp;{badge}' if badge else "")]
    for label, key in (("Description", "description"), ("Period", "period"),
                       ("Occurrences", "occurrences"), ("RCA", "rca"),
                       ("Responsible Team", "responsible_team")):
        if item[key]:
            lines.append(
                f'<span style="color: #64748b;">{label}:</span> {esc(item[key])}')
    return ('<div style="margin-top: 6px; padding: 8px 10px; background-color: #f8fafc; border: 1px solid #e2e8f0; '
            f'border-left: 3px solid {border}; border-radius: 4px; font-size: 12px; line-height: 1.5; color: #475569;">'
            + "<br/>".join(lines) + "</div>")


def _bucket_for(item: dict, status_val: str) -> str:
    if item["component"] == "MDM":
        return "mdm"
    if item["component"] in BMS_MOTOR_COMPONENTS:
        return "bms"
    if status_val == "mdm_issue" and not item["structured"]:
        return "mdm"
    title = item["title"].lower()
    if "data loss" in title:
        return "data_loss"
    if "plug state 4" in title or "charging" in title:
        return "charging"
    return "bms"


def _entry(head: str, items: list) -> str:
    """Vehicle entry for one row: head text + a block for each structured issue."""
    return head + "".join(issue_block_html(i) for i in items if i["structured"])


def _legacy_titles(items: list) -> str:
    return ", ".join(i["title"] for i in items if not i["structured"])


def category_data(vehicles: dict) -> dict:
    """Counts for the Issue Category Summary and the Data / Telemetry table."""
    counts = {c[0]: 0 for c in CATEGORY_DEFS}
    affected = {c[0]: [] for c in CATEGORY_DEFS}
    affected_details = {c[0]: [] for c in CATEGORY_DEFS}
    telemetry = []
    any_structured = False
    for vin, val in sorted(vehicles.items()):
        if val.get("status", "healthy") not in ISSUE_STATUSES:
            continue
        nick = get_short_nickname(val.get("nickname", ""))
        mdm_items = []
        for it in vehicle_issue_items(val):
            if not it["structured"]:
                continue
            any_structured = True
            comp = it["component"]
            if comp in counts:
                counts[comp] += 1
                if nick not in affected[comp]:
                    affected[comp].append(nick)
                    affected_details[comp].append({"vin": vin, "nick": nick})
            if comp == "MDM":
                mdm_items.append(it)
        if mdm_items:
            telemetry.append({"vin": vin, "nick": nick, "items": mdm_items})
    return {"counts": counts, "affected": affected, "affected_details": affected_details,
            "telemetry": telemetry, "any_structured": any_structured}


