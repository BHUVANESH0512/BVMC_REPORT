#!/usr/bin/env python3
"""
Shared, dependency-free helpers for the Issue Summary part of the mission report.

Both app.py and vehicle_mission_report-4.py call into this module, so the Issue
Summary, the "Issue Category Summary" / "Data / Telemetry Issues" tables and the
per-vehicle issue table are generated by exactly one implementation.  The
JavaScript in vehicle_mission_report-4.html (buildIssueSummaryHTML and friends)
is a line-by-line port of these functions and must be kept in sync.

Customer Feedback is a plain-text field typed by the owner for each issue; it is
stored with the other issue fields and HTML-escaped whenever it is rendered.
"""

import html
import re

COMPONENTS = ["BMS", "Motor", "DCDC", "EPAS", "MDM", "Other"]
SEVERITIES = ["Low", "Medium", "High", "Critical"]
BMS_MOTOR_COMPONENTS = ("BMS", "Motor", "DCDC")
ISSUE_STATUSES = ("unhealthy", "mdm_issue")
MAX_FIELD_LEN = 2000

# (component, table label, icon, icon background)
CATEGORY_DEFS = [
    ("BMS", "BMS Issues", "🔋", "#dc2626"),
    ("EPAS", "EPAS Issues", "🚗", "#2563eb"),
    ("DCDC", "DCDC Issues", "🔌", "#0d9488"),
    ("Motor", "Motor Faults", "⚙️", "#ea580c"),
    ("MDM", "Data / Telemetry Issues", "📶", "#7c3aed"),
]

# severity -> (badge background, badge text colour)
SEVERITY_STYLES = {
    "Low": ("#dcfce7", "#16a34a"),
    "Medium": ("#ffedd5", "#ea580c"),
    "High": ("#fee2e2", "#dc2626"),
    "Critical": ("#991b1b", "#ffffff"),
}
# severity -> accent colour of the left border of an issue block
SEVERITY_BORDERS = {"Low": "#16a34a", "Medium": "#ea580c",
                    "High": "#dc2626", "Critical": "#991b1b"}

MAX_FEEDBACK_LEN = 1000


# ------------------------------------------------------------------
# Small helpers
# ------------------------------------------------------------------

def esc(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def clean_text(value, limit: int = MAX_FIELD_LEN) -> str:
    if value is None:
        return ""
    text = str(value)
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text).strip()
    return text[:limit]


def clean_url(value) -> str:
    """A Grafana link must be a plain http(s) address; anything else is dropped."""
    url = clean_text(value, 500)
    return url if re.match("https?://[^\\s<>\"']+$", url, re.I) else ""


def get_short_nickname(nickname: str) -> str:
    name = re.sub(r'\s*Vehicle.*', '', nickname)
    name = re.sub(r'\s*\(.*?\)', '', name)
    if name == "US HC Fargo":
        return "USHC Fargo"
    if name == "US HC Yuba":
        return "USHC Yuba"
    return name.strip()


# ------------------------------------------------------------------
# Issue items (structured details + legacy plain-text issues)
# ------------------------------------------------------------------

def vehicle_issue_items(val: dict) -> list:
    """Return one dict per issue of a vehicle.

    A vehicle stores `issues` (plain titles, the original format) and, for new
    data, `issue_details` (one dict per issue with the new fields).  An item is
    "structured" only when it carries a valid Component; every other item is
    treated exactly like an old plain-text issue.
    """
    issues = val.get("issues") or []
    details = val.get("issue_details") or []
    if not isinstance(issues, list):
        issues = []
    if not isinstance(details, list):
        details = []
    count = max(len(issues), len(details)) if details else len(issues)

    items = []
    used_ids = set()
    for idx in range(count):
        d = details[idx] if idx < len(details) and isinstance(
            details[idx], dict) else {}
        legacy_title = clean_text(issues[idx]) if idx < len(issues) else ""
        component = clean_text(d.get("component"))
        if component not in COMPONENTS:
            component = ""
        severity = clean_text(d.get("severity"))
        if severity not in SEVERITIES:
            severity = ""
        issue_id = re.sub(r"[^A-Za-z0-9_-]", "", clean_text(d.get("id"), 64))
        if not issue_id or issue_id in used_ids:
            issue_id = f"i{idx + 1}"
        used_ids.add(issue_id)
        items.append({
            "id": issue_id,
            "title": clean_text(d.get("issue")) or legacy_title,
            "description": clean_text(d.get("description")),
            "period": clean_text(d.get("period")),
            "occurrences": clean_text(d.get("occurrences")),
            "component": component,
            "reported_by": clean_text(d.get("reported_by")),
            "severity": severity,
            "rca": clean_text(d.get("rca")),
            "responsible_team": clean_text(d.get("responsible_team")),
            "customer_feedback": clean_text(d.get("customer_feedback"), MAX_FEEDBACK_LEN),
            "grafana_url": clean_url(d.get("grafana_url")),
            "structured": bool(component),
        })
    return items


def normalize_vehicle(val: dict) -> dict:
    """Return a copy of a vehicle with clean, aligned `issues`/`issue_details`.

    Old vehicles (no `issue_details`) keep their `issues` list unchanged.
    """
    out = dict(val)
    if out.get("status", "healthy") not in ISSUE_STATUSES or not (val.get("issue_details") or []):
        out["issue_details"] = []
        return out
    items = vehicle_issue_items(val)
    details = []
    for it in items:
        d = {
            "id": it["id"],
            "issue": it["title"],
            "description": it["description"],
            "period": it["period"],
            "occurrences": it["occurrences"],
            "component": it["component"],
            "reported_by": it["reported_by"],
            "severity": it["severity"],
            "rca": it["rca"],
            "responsible_team": it["responsible_team"],
            "customer_feedback": it["customer_feedback"],
            "grafana_url": it["grafana_url"],
        }
        details.append(d)
    out["issue_details"] = details
    out["issues"] = [it["title"] for it in items]
    return out


def normalize_vehicles(vehicles: dict) -> dict:
    result = {}
    for vin, val in (vehicles or {}).items():
        result[vin] = normalize_vehicle(val) if isinstance(val, dict) else val
    return result


def validate_vehicles(vehicles: dict) -> list:
    """Return a list of human-readable problems (empty when everything is valid)."""
    problems = []
    for vin, val in (vehicles or {}).items():
        if not isinstance(val, dict) or val.get("status") not in ISSUE_STATUSES:
            continue
        for idx, it in enumerate(vehicle_issue_items(val), start=1):
            if it["structured"] and (not it["title"] or not it["description"]):
                problems.append(
                    f"Vehicle {vin}, issue {idx}: both Issue and Description are required.")
    return problems


